import fs from "node:fs";
import path from "node:path";
import { validateActiveSessionPolicy } from "./active-session-policy.mjs";

const base = process.cwd();
const categoryCatalog = fs.readFileSync(path.join(base, "src/learning/categoryCatalog.ts"), "utf8");
const activation = JSON.parse(fs.readFileSync(path.join(base, "public/content/activation/active-sessions.json"), "utf8"));
const outputPath = path.join(base, "src/learning/contentIntegrity.generated.ts");
const categoryPattern = /(reading_units|vowels_sukun|shaddah|article_al|linking|fluent_reading):\s*\{[\s\S]*?manifestUrl:\s*"([^"]+)"[\s\S]*?blueprintUrl:\s*"([^"]+)"/g;
const resources = [];
let match;
while ((match = categoryPattern.exec(categoryCatalog)) !== null) {
  resources.push({ category: match[1], manifestUrl: match[2], blueprintUrl: match[3] });
}

if (resources.length !== 6) {
  throw new Error(`Expected 6 category resources, found ${resources.length}.`);
}

const fingerprints = {};
for (const { category, manifestUrl, blueprintUrl } of resources) {
  const manifest = JSON.parse(fs.readFileSync(path.join(base, manifestUrl.replace(/^\//, "public/")), "utf8"));
  const blueprint = JSON.parse(fs.readFileSync(path.join(base, blueprintUrl.replace(/^\//, "public/")), "utf8"));
  const activeSessionIds = validateActiveSessionPolicy({ category, blueprint, manifest, activation });
  const items = new Map((manifest.items ?? []).map((item) => [item.id, item]));
  const categoryFingerprints = {};

  for (const sessionId of activeSessionIds) {
    const session = blueprint.sessions.find((candidate) => candidate.id === sessionId);
    if (!session) throw new Error(`Missing active controlled session ${category}/${sessionId}.`);
    for (const interaction of session.interactions) {
      const item = items.get(interaction.itemId);
      if (!item) throw new Error(`Missing controlled item ${interaction.itemId}.`);
      const fingerprint = {
        utf8Sha256: item.integrity.utf8Sha256,
        sourceId: item.source.sourceId,
        pdfPage: item.source.pdfPage,
      };
      const existing = categoryFingerprints[item.id];
      if (existing && JSON.stringify(existing) !== JSON.stringify(fingerprint)) {
        throw new Error(`Conflicting controlled fingerprint for ${category}/${item.id}.`);
      }
      categoryFingerprints[item.id] = fingerprint;
    }
  }
  fingerprints[category] = categoryFingerprints;
}

const source = `// Generated by scripts/generate-content-integrity-registry.mjs. Do not edit by hand.\nimport type { ExerciseCategory } from "./types";\n\nexport type ControlledContentFingerprint = {\n  utf8Sha256: string;\n  sourceId: string;\n  pdfPage: number;\n};\n\nconst CONTROLLED_CONTENT_FINGERPRINTS: Record<ExerciseCategory, Record<string, ControlledContentFingerprint>> = ${JSON.stringify(fingerprints, null, 2)};\n\nexport function controlledContentFingerprintForItem(\n  category: ExerciseCategory,\n  itemId: string,\n): ControlledContentFingerprint | undefined {\n  return CONTROLLED_CONTENT_FINGERPRINTS[category]?.[itemId];\n}\n`;

fs.writeFileSync(outputPath, source, "utf8");
console.log(`Generated controlled content fingerprints for ${resources.length} categories.`);