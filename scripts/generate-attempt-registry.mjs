import fs from "node:fs";
import path from "node:path";

const base = process.cwd();
const categoryCatalogPath = path.join(base, "src/learning/categoryCatalog.ts");
const outputPath = path.join(base, "src/learning/attemptRegistry.generated.ts");
const categoryCatalog = fs.readFileSync(categoryCatalogPath, "utf8");
const categoryPattern = /(reading_units|vowels_sukun|shaddah|article_al|linking|fluent_reading):\s*\{[\s\S]*?manifestUrl:\s*"([^"]+)"[\s\S]*?blueprintUrl:\s*"([^"]+)"/g;
const arabicPattern = /[\u0600-\u06ff]/u;
const resources = [];
let match;
while ((match = categoryPattern.exec(categoryCatalog)) !== null) {
  resources.push({ category: match[1], manifestUrl: match[2], blueprintUrl: match[3] });
}

if (resources.length !== 6) {
  throw new Error(`Expected 6 active category resources, found ${resources.length}.`);
}

const registry = {};
const availableSessions = {};
for (const { category, manifestUrl, blueprintUrl } of resources) {
  const blueprintPath = blueprintUrl.replace(/^\//, "public/");
  const manifestPath = manifestUrl.replace(/^\//, "public/");
  const blueprint = JSON.parse(fs.readFileSync(path.join(base, blueprintPath), "utf8"));
  const manifest = JSON.parse(fs.readFileSync(path.join(base, manifestPath), "utf8"));
  if (blueprint.category !== category) {
    throw new Error(`Category mismatch for ${blueprintUrl}: expected ${category}, got ${blueprint.category}.`);
  }
  const manifestItems = new Map((manifest.items ?? []).map((item) => [item.id, item]));
  const sessions = {};
  const activeSessionIds = [];
  for (const session of blueprint.sessions ?? []) {
    if (typeof session.id !== "string" || session.id.length === 0 || arabicPattern.test(session.id)) {
      throw new Error(`Invalid session id in ${blueprintUrl}.`);
    }
    const itemIds = [];
    let sessionAvailable = true;
    for (const interaction of session.interactions ?? []) {
      if (typeof interaction.itemId !== "string" || interaction.itemId.length === 0 || arabicPattern.test(interaction.itemId)) {
        throw new Error(`Invalid item id in ${blueprintUrl}/${session.id}.`);
      }
      itemIds.push(interaction.itemId);
      const item = manifestItems.get(interaction.itemId);
      if (!item || item.active !== true || item.eligibleForActiveLesson !== true) {
        sessionAvailable = false;
      }
    }
    sessions[session.id] = itemIds;
    if (sessionAvailable && itemIds.length > 0) activeSessionIds.push(session.id);
  }
  registry[category] = sessions;
  availableSessions[category] = activeSessionIds;
}

const source = `// Generated by scripts/generate-attempt-registry.mjs. Do not edit by hand.\nimport type { AttemptRecord, ExerciseCategory } from "./types";\n\nconst AUTHORIZED_ATTEMPTS: Record<ExerciseCategory, Record<string, readonly string[]>> = ${JSON.stringify(registry, null, 2)};\n\nconst AVAILABLE_SESSIONS: Record<ExerciseCategory, readonly string[]> = ${JSON.stringify(availableSessions, null, 2)};\n\nexport function isAttemptAuthorizedByControlledBlueprint(\n  attempt: Pick<AttemptRecord, "category" | "sessionId" | "itemId">,\n): boolean {\n  return AUTHORIZED_ATTEMPTS[attempt.category]?.[attempt.sessionId]?.includes(attempt.itemId) ?? false;\n}\n\nexport function isSessionAvailableForActiveLesson(\n  category: ExerciseCategory,\n  sessionId: string,\n): boolean {\n  return AVAILABLE_SESSIONS[category]?.includes(sessionId) ?? false;\n}\n\nexport function hasSessionAvailableForActiveLesson(category: ExerciseCategory): boolean {\n  return (AVAILABLE_SESSIONS[category]?.length ?? 0) > 0;\n}\n\nfunction correctAttemptCounts(\n  attempts: AttemptRecord[],\n  category: ExerciseCategory,\n  sessionId: string,\n): Map<string, number> {\n  const counts = new Map<string, number>();\n  for (const attempt of attempts) {\n    if (attempt.category !== category || attempt.sessionId !== sessionId || attempt.outcome !== "correct") continue;\n    counts.set(attempt.itemId, (counts.get(attempt.itemId) ?? 0) + 1);\n  }\n  return counts;\n}\n\nexport function sessionResumeIndexFromAuthorizedAttempts(\n  category: ExerciseCategory,\n  sessionId: string,\n  attempts: AttemptRecord[],\n): number {\n  const requiredItemIds = AUTHORIZED_ATTEMPTS[category]?.[sessionId];\n  if (!requiredItemIds?.length) return 0;\n  const correctCounts = correctAttemptCounts(attempts, category, sessionId);\n  const consumed = new Map<string, number>();\n  for (let index = 0; index < requiredItemIds.length; index += 1) {\n    const itemId = requiredItemIds[index];\n    const requiredOccurrence = (consumed.get(itemId) ?? 0) + 1;\n    if ((correctCounts.get(itemId) ?? 0) < requiredOccurrence) return index;\n    consumed.set(itemId, requiredOccurrence);\n  }\n  return 0;\n}\n\nexport function completedSessionIdsFromAuthorizedAttempts(attempts: AttemptRecord[]): string[] {\n  const completed: string[] = [];\n  for (const category of Object.keys(AUTHORIZED_ATTEMPTS) as ExerciseCategory[]) {\n    for (const [sessionId, requiredItemIds] of Object.entries(AUTHORIZED_ATTEMPTS[category])) {\n      const requiredCounts = new Map<string, number>();\n      for (const itemId of requiredItemIds) {\n        requiredCounts.set(itemId, (requiredCounts.get(itemId) ?? 0) + 1);\n      }\n      const correctCounts = correctAttemptCounts(attempts, category, sessionId);\n      if (Array.from(requiredCounts.entries()).every(([itemId, count]) => (correctCounts.get(itemId) ?? 0) >= count)) {\n        completed.push(sessionId);\n      }\n    }\n  }\n  return completed;\n}\n`;

fs.writeFileSync(outputPath, source, "utf8");
console.log(`Generated controlled attempt registry for ${resources.length} categories.`);
