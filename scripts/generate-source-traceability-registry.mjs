import fs from "node:fs";
import path from "node:path";

const base = process.cwd();
const categoryCatalogPath = path.join(base, "src/learning/categoryCatalog.ts");
const outputPath = path.join(base, "src/learning/sourceTraceability.generated.ts");
const arabicPattern = /[\u0600-\u06ff]/u;

const categoryCatalog = fs.readFileSync(categoryCatalogPath, "utf8");
const manifestPattern = /manifestUrl:\s*"([^"]+)"/g;
const manifestUrls = [];
let match;
while ((match = manifestPattern.exec(categoryCatalog)) !== null) {
  manifestUrls.push(match[1]);
}

const uniqueManifestUrls = [...new Set(manifestUrls)];
if (!uniqueManifestUrls.length) {
  throw new Error("No controlled manifest resources found in category catalog.");
}

const bySource = new Map();
for (const manifestUrl of uniqueManifestUrls) {
  const manifestPath = path.join(base, manifestUrl.replace(/^\//, "public/"));
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  const sourceControl = manifest.sourceControl ?? {};
  const sourceId = sourceControl.canonicalSourceId;
  const batchId = manifest.batchId;
  const verifiedPdfPages = sourceControl.verifiedPdfPages;

  if (typeof sourceId !== "string" || !sourceId || arabicPattern.test(sourceId)) {
    throw new Error(`Invalid controlled source id in ${manifestUrl}.`);
  }
  if (typeof batchId !== "string" || !batchId || arabicPattern.test(batchId)) {
    throw new Error(`Invalid controlled batch id in ${manifestUrl}.`);
  }
  if (
    !Array.isArray(verifiedPdfPages)
    || !verifiedPdfPages.length
    || verifiedPdfPages.some((page) => !Number.isInteger(page) || page <= 0)
  ) {
    throw new Error(`Invalid verified PDF pages in ${manifestUrl}.`);
  }
  if (sourceControl.visualPassesPerItem !== 2) {
    throw new Error(`Controlled source ${sourceId} must use two visual passes per item.`);
  }
  if (sourceControl.silentNormalization !== false) {
    throw new Error(`Controlled source ${sourceId} must forbid silent normalization.`);
  }
  if (sourceControl.ocrUsedAsAuthority !== false) {
    throw new Error(`Controlled source ${sourceId} must not use OCR as authority.`);
  }

  const existing = bySource.get(sourceId) ?? {
    sourceId,
    batchIds: new Set(),
    verifiedPdfPages: new Set(),
    visualPassesPerItem: 2,
    silentNormalization: false,
    ocrUsedAsAuthority: false,
  };

  existing.batchIds.add(batchId);
  for (const page of verifiedPdfPages) existing.verifiedPdfPages.add(page);
  bySource.set(sourceId, existing);
}

const sources = [...bySource.values()]
  .map((source) => ({
    sourceId: source.sourceId,
    batchIds: [...source.batchIds].sort(),
    verifiedPdfPages: [...source.verifiedPdfPages].sort((a, b) => a - b),
    visualPassesPerItem: source.visualPassesPerItem,
    silentNormalization: source.silentNormalization,
    ocrUsedAsAuthority: source.ocrUsedAsAuthority,
  }))
  .sort((a, b) => a.sourceId.localeCompare(b.sourceId));

const source = `// Generated by scripts/generate-source-traceability-registry.mjs. Do not edit by hand.\n\nexport type ControlledSourceTraceability = {\n  sourceId: string;\n  batchIds: readonly string[];\n  verifiedPdfPages: readonly number[];\n  visualPassesPerItem: 2;\n  silentNormalization: false;\n  ocrUsedAsAuthority: false;\n};\n\nexport const CONTROLLED_SOURCE_TRACEABILITY: readonly ControlledSourceTraceability[] = ${JSON.stringify(sources, null, 2)};\n`;

if (arabicPattern.test(source)) {
  throw new Error("Generated source traceability registry contains Arabic text.");
}

fs.writeFileSync(outputPath, source, "utf8");
console.log(`Generated controlled source traceability for ${sources.length} source(s) from ${uniqueManifestUrls.length} manifest(s).`);
